export type ChatOptionLetter = 'А' | 'Б' | 'В'

export interface LegalChatMessage {
  id: string
  sender: string
  roleLabel: string
  side: 'left' | 'right'
  text: string
}

export interface LegalChatOption {
  letter: ChatOptionLetter
  text: string
  /** Пояснение, почему данный вариант неверен (для неверных ответов) */
  whyWrong?: string
}

export interface LegalChatNormativeBasis {
  article: string
  title: string
  codePart: 'Общая часть ГК РК' | 'Особенная часть ГК РК'
  summary: string
  sourceUrl: string
}

