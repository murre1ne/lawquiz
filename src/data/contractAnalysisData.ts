export interface ContractAnalysisStep {
  stepNumber: number
  /** Название этапа (без номеров статей — статьи отображаются в блоке «Правовая основа») */
  title: string
  /** Компактная подпись этапа для пошагового индикатора */
  shortLabel: string
  /** Фрагмент учебного договора */
  fragment: string
  /** Юридический разбор простыми словами */
  explanation: string[]
  /** Опциональная формула расчёта, отображаемая внутри разбора */
  formula?: string
  /** Продолжение разбора после формулы (если применимо) */
  explanationAfterFormula?: string[]
  /** Главный вывод этапа («Что необходимо запомнить») */
  takeaway: string
  /** Правовая основа (статьи ГК РК) */
  legalBasis: string
  /** Официальные ссылки на ИПС «Әділет» для данного этапа */
  sources: ContractSourceLink[]
}

