export function getTopicById(topicId: string): LibraryTopic | undefined {
  for (const cat of libraryCategoriesData) {
    const found = cat.topics.find((t) => t.id === topicId)
    if (found) return found
  }
  return undefined
}

export function getCategoryById(categoryId: string): LibraryCategoryData | undefined {
  return libraryCategoriesData.find((cat) => cat.id === categoryId)
}

export function getCategoryByTopicId(topicId: string): LibraryCategoryData | undefined {
  return libraryCategoriesData.find((cat) => cat.topics.some((t) => t.id === topicId))
}
