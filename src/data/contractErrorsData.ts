export function getContractAuditGrade(score: number): string {
  if (score === 4) return 'Отличная юридическая подготовка!'
  if (score === 3) return 'Хороший результат!'
  if (score === 2) return 'Есть понимание основ, но стоит повторить нормы ГК РК'
  return 'Рекомендуем повторить материал и пройти практику ещё раз'
}
